#!/usr/bin/env bash
# =====================================================================
#  9rayaverse — one-command install on Ubuntu 22.04 / 24.04
#  (Oracle Cloud Free Tier, Hetzner, OVH, DigitalOcean, ...)
#
#  Usage (on the server):
#    sudo git clone https://github.com/YOU/9rayaverse.git /var/www/9rayaverse
#    sudo bash /var/www/9rayaverse/deploy/install.sh [domain] [email]
#
#  With a domain + email you get HTTPS (Let's Encrypt) and the app becomes installable.
#  Safe to run again: it keeps an existing config.php and database.
# =====================================================================
set -euo pipefail

DOMAIN="${1:-}"
EMAIL="${2:-}"
APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WS_PORT=8080

say()  { printf '\n\033[1;35m==> %s\033[0m\n' "$*"; }
fail() { printf '\n\033[1;31m✖ %s\033[0m\n' "$*"; exit 1; }

[ "$(id -u)" -eq 0 ] || fail "Lezem t5addmou b sudo:  sudo bash $0 $*"
[ -f "$APP_DIR/database.sql" ] || fail "Ma l9itech database.sql fi $APP_DIR"
if [ -n "$DOMAIN" ] && [ -z "$EMAIL" ]; then fail "Bech ta5ou HTTPS 7ott zeda email:  sudo bash $0 $DOMAIN email@mte3ek.com"; fi

export DEBIAN_FRONTEND=noninteractive

say "1/8 Nsobbou les paquets (Nginx, PHP, MariaDB, Git)"
apt-get update -y
apt-get install -y nginx mariadb-server php-fpm php-mysql php-mbstring php-xml php-curl curl ca-certificates gnupg git openssl rsync

say "2/8 Node.js"
NODE_MAJOR=0
if command -v node >/dev/null 2>&1; then NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"; fi
if [ "$NODE_MAJOR" -lt 18 ]; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
  apt-get install -y nodejs
fi
NODE_BIN="$(command -v node)"
echo "Node $(node -v)"

PHPV="$(php -r 'echo PHP_MAJOR_VERSION.".".PHP_MINOR_VERSION;')"
echo "PHP $PHPV"

say "3/8 Base de données"
systemctl enable --now mariadb
if [ -f "$APP_DIR/config.php" ]; then
  echo "config.php mawjoud → nkhalliweh (w l'base kima hiya)."
else
  DB_PASS="$(openssl rand -hex 16)"
  WS_SECRET="$(openssl rand -hex 32)"
  if mysql -e 'USE rayaverse' 2>/dev/null; then
    echo "Base 'rayaverse' mawjouda deja → ma nfaskhouhech."
  else
    mysql < "$APP_DIR/database.sql"
  fi
  mysql -e "CREATE USER IF NOT EXISTS 'rayaverse'@'localhost' IDENTIFIED BY '$DB_PASS';
            ALTER USER 'rayaverse'@'localhost' IDENTIFIED BY '$DB_PASS';
            GRANT ALL PRIVILEGES ON rayaverse.* TO 'rayaverse'@'localhost';
            FLUSH PRIVILEGES;"

  say "4/8 config.php (mots de passe jdod, random)"
  cat > "$APP_DIR/config.php" <<EOF
<?php
// Generated by deploy/install.sh on $(date -u +%F). Keep this file private.
define('DB_HOST', 'localhost');
define('DB_NAME', 'rayaverse');
define('DB_USER', 'rayaverse');
define('DB_PASS', '$DB_PASS');

define('WS_SECRET', '$WS_SECRET');
define('WS_PORT', $WS_PORT);
define('WS_PUBLIC_URL', '/ws');

define('APP_DEBUG', false);
define('APP_TIMEZONE', 'Africa/Tunis');

define('MAX_PDF_MB', 20);
define('MAX_IMAGE_MB', 3);
EOF
fi

say "5/8 PHP (upload 25 Mo) + permissions"
cat > "/etc/php/$PHPV/fpm/conf.d/99-rayaverse.ini" <<EOF
upload_max_filesize = 25M
post_max_size = 26M
expose_php = Off
date.timezone = Africa/Tunis
EOF
mkdir -p "$APP_DIR/uploads/avatars" "$APP_DIR/uploads/courses" "$APP_DIR/uploads/proofs"
git config --global --add safe.directory "$APP_DIR" || true
chown -R www-data:www-data "$APP_DIR"
chmod 640 "$APP_DIR/config.php"
systemctl restart "php$PHPV-fpm"

say "6/8 Serveur temps réel (Node.js + systemd)"
(cd "$APP_DIR/ws-server" && npm install --omit=dev --no-audit --no-fund)
chown -R www-data:www-data "$APP_DIR/ws-server"
sed -e "s#__APP_DIR__#$APP_DIR#g" -e "s#__NODE__#$NODE_BIN#g" "$APP_DIR/deploy/rayaverse-ws.service" > /etc/systemd/system/rayaverse-ws.service
systemctl daemon-reload
systemctl enable --now rayaverse-ws
systemctl restart rayaverse-ws

say "7/8 Nginx + firewall"
sed -e "s#__DOMAIN__#${DOMAIN:-_}#g" -e "s#__APP_DIR__#$APP_DIR#g" -e "s#__PHPV__#$PHPV#g" -e "s#__WS_PORT__#$WS_PORT#g" \
  "$APP_DIR/deploy/nginx.conf" > /etc/nginx/sites-available/rayaverse
ln -sf /etc/nginx/sites-available/rayaverse /etc/nginx/sites-enabled/rayaverse
rm -f /etc/nginx/sites-enabled/default
nginx -t
systemctl enable --now nginx
systemctl reload nginx

# Oracle Cloud Ubuntu images block everything except SSH with iptables: open 80/443.
if command -v iptables >/dev/null 2>&1 && iptables -S INPUT 2>/dev/null | grep -q REJECT; then
  for p in 80 443; do
    iptables -C INPUT -p tcp --dport "$p" -j ACCEPT 2>/dev/null || iptables -I INPUT 1 -p tcp --dport "$p" -j ACCEPT
  done
  if command -v netfilter-persistent >/dev/null 2>&1; then netfilter-persistent save; fi
fi
if command -v ufw >/dev/null 2>&1 && ufw status | grep -q "Status: active"; then
  ufw allow OpenSSH
  ufw allow 'Nginx Full'
fi

# Daily backup of the database + uploads (keeps 14 days).
install -m 755 "$APP_DIR/deploy/backup.sh" /usr/local/bin/rayaverse-backup
echo "30 3 * * * root APP_DIR=$APP_DIR /usr/local/bin/rayaverse-backup >/dev/null 2>&1" > /etc/cron.d/rayaverse-backup

say "8/8 HTTPS"
if [ -n "$DOMAIN" ]; then
  apt-get install -y certbot python3-certbot-nginx
  certbot --nginx -d "$DOMAIN" -m "$EMAIL" --agree-tos --non-interactive --redirect || \
    echo "⚠️  HTTPS ma tsobbech: thabbet elli l'domaine $DOMAIN ychouf 3al IP mta3 l'serveur, ba3d 3awed: sudo certbot --nginx -d $DOMAIN"
  URL="https://$DOMAIN"
else
  URL="http://$(curl -fsS -4 https://ifconfig.me 2>/dev/null || hostname -I | awk '{print $1}')"
  echo "Bla domaine → l'site b http bark (l'app ma tetsobbech 3al téléphone 7atta yebda fama HTTPS)."
fi

say "✅ 9rayaverse jahez: $URL"
echo "👑 Od5ol tawa w a3mel l'compte mte3ek l'AWEL — howa elli ywalli Admin général."
echo "   Mise à jour ba3d:  sudo bash $APP_DIR/deploy/update.sh"
